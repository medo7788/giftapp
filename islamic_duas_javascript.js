// Functions to retrieve duas
function getDuaByDate(month, day) {
  if (islamicDuas[month] && islamicDuas[month][day - 1]) {
    return islamicDuas[month][day - 1];
  }
  return null;
}

function getTodaysDua() {
  const today = new Date();
  const monthNames = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December"
  ];
  const month = monthNames[today.getMonth()];
  const day = today.getDate();
  return getDuaByDate(month, day);
}

function getMonthDuas(month) {
  return islamicDuas[month] || [];
}

